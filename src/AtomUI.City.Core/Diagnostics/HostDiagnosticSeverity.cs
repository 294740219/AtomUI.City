namespace AtomUI.City.Core.Diagnostics;

/// <summary>
/// Defines the supported values for host diagnostic severity.
/// </summary>
public enum HostDiagnosticSeverity
{
    /// <summary>
    /// Represents the trace option.
    /// </summary>
    Trace,
    /// <summary>
    /// Represents the info option.
    /// </summary>
    Info,
    /// <summary>
    /// Represents the warning option.
    /// </summary>
    Warning,
    /// <summary>
    /// Represents the error option.
    /// </summary>
    Error,
}
