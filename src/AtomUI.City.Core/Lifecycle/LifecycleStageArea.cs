namespace AtomUI.City.Core.Lifecycle;

/// <summary>
/// Defines the supported values for lifecycle stage area.
/// </summary>
public enum LifecycleStageArea
{
    /// <summary>
    /// Represents the application option.
    /// </summary>
    Application,
    /// <summary>
    /// Represents the module option.
    /// </summary>
    Module,
    /// <summary>
    /// Represents the plugin option.
    /// </summary>
    Plugin,
    /// <summary>
    /// Represents the route option.
    /// </summary>
    Route,
    /// <summary>
    /// Represents the activation option.
    /// </summary>
    Activation,
    /// <summary>
    /// Represents the operation option.
    /// </summary>
    Operation,
    /// <summary>
    /// Represents the error option.
    /// </summary>
    Error,
}
